import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {inspectCharacter,readJson} from './lib/character-pipeline.mjs';
import {sourceDamageEvents} from './lib/source-damage-events.mjs';
import {validateActionChoreography} from '../src/effects/actionChoreography.mjs';
import {validateSceneAction} from '../src/effects/sceneProfile.mjs';

test('Iai Strike uses the complete source composition, independent command/body tracks and separate balance',()=>{
 const recipe=readJson('tools/characters/jack.json');
 const report=inspectCharacter(recipe,{assets:'assets',dump:'ffbe_asset_dump-main'});
 assert.equal(report.publishable,true,JSON.stringify(report.selected));
 const skill=readJson('public/assets/units/jack/skills.json').skills.find(s=>s.ffbeId===200300);
 const body=readJson('public/assets/units/jack/manifest.json');
 const manifest=readJson('public/assets/presentations/'+skill.scenePresentation+'/manifest.json');
 const source=report.catalog.find(s=>s.id===skill.ffbeId),plan=manifest.plan;
 validateSceneAction(manifest,skill);validateActionChoreography(skill,manifest.durationFrames,body.animations);
 assert.deepEqual(skill.originalCommand.raw,JSON.parse(JSON.stringify(source.raw)));
 assert.equal(source.raw.processId,'112');assert.equal(source.raw.processParam,'1400,70,100,0');
 assert.equal(skill.mpCost,20);assert.equal(skill.damageMultiplier,0);
 assert.equal(skill.scope,'all_enemies');assert.equal(skill.moveType,'stationary');
 assert.equal(plan.composition.skillFrameOffset,0);assert.equal(plan.effects.length,1);assert.equal(plan.members.length,1);
 assert.equal(plan.effects[0].sha256,'4ef468a09b4e8f3f51f45a86c61bd52a9db25ce31daf82b2664c769cb8112e6b');
 assert.equal(plan.effects[0].nodes.length,3);assert.equal(plan.effects[0].nodes[2].typeId,6);
 assert.deepEqual(sourceDamageEvents(source,plan),[{frame:45,weight:1}]);
 assert.deepEqual(skill.supportEvents,[{frame:45,effects:[{kind:'execute-or-damage',chance:.3,fallbackDamage:700,bossImmune:true}]}]);
 assert.equal(skill.damageEvents,undefined);assert.equal(skill.hitCount,1);assert.equal(recipe.skills.find(s=>s.ffbeId===200300).execution,'prepared-events');
 const c=skill.actionChoreography;
 assert.equal(c.commandPose,'standby');assert.equal(c.readiness,'none');
 assert.deepEqual(c.body,{mode:'clips',phases:[{frame:0,clip:'magic_atk'}]});
 assert.equal(plan.members[0].scalePercent,250);assert.equal(plan.members[0].startFrame,41);
 assert.equal(plan.members[0].placement.rectangle,'target-side');assert.deepEqual(plan.members[0].placement.offset,[80,0]);
 assert.equal(manifest.originalFidelityVerified,false);
 const wrong=structuredClone(recipe);delete wrong.skills.find(s=>s.ffbeId===200300).actionChoreography;
 assert.equal(inspectCharacter(wrong,{assets:'assets',dump:'ffbe_asset_dump-main'}).publishable,false);
 const badScope=structuredClone(recipe);badScope.skills.find(s=>s.ffbeId===200300).scope='single_enemy';
 assert.ok(inspectCharacter(badScope,{assets:'assets',dump:'ffbe_asset_dump-main'}).selected.some(s=>s.issues.includes('original-target-scope-review-mismatch')));
 assert.ok(fs.existsSync('public/assets/units/jack/magic_atk.png'));
});
