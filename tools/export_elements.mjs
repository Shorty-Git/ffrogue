// Exports original FFBE element data into src/run/elements.mjs, so element gameplay and balancing work
// without the raw database (cloud sessions have no rawdata/):
//  - enemies: monster_parts.elemResistValue (percent; negative = weakness) per ENEMY_CONTENT key,
//  - enemySkills: monster_skill.elementInflict per published enemy skill (tools/monsters/skills/*),
//  - heroes: unit.elemResistValue of each published hero's sprite unit.
// Hero skill elements need no export: published skills carry originalCommand.raw.element.
// Usage: node tools/export_elements.mjs [--assets rawdata/assets] [--check]
import fs from 'node:fs';
import path from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {ENEMY_CONTENT} from '../src/run/stageContent.mjs';

export const ELEMENTS = ['fire', 'ice', 'lightning', 'water', 'wind', 'earth', 'light', 'dark'];
const args = process.argv.slice(2), check = args.includes('--check');
const assets = args.includes('--assets') ? args[args.indexOf('--assets') + 1] : 'rawdata/assets';
const db = new DatabaseSync(path.join(assets, 'static_data/ffbe-data.db'), {readOnly: true});
const read = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const resist = raw => {
  const values = String(raw ?? '').split(',').map(Number);
  return Object.fromEntries(ELEMENTS.map((element, i) => [element, values[i] || 0]).filter(([, v]) => v));
};
const inflict = raw => ELEMENTS.filter((_, i) => Number(String(raw ?? '').split(',')[i]) > 0);

const enemies = {}, enemySkills = {}, heroes = {};
for (const [key, enemy] of Object.entries(ENEMY_CONTENT)) {
  const row = db.prepare('SELECT elemResistValue FROM monster_parts WHERE monsterId = ? ORDER BY partsNum LIMIT 1').get(Number(enemy.monsterId));
  if (!row) throw Error(`No monster_parts row for ${key} (${enemy.monsterId})`);
  enemies[key] = resist(row.elemResistValue);
}
for (const file of fs.readdirSync('tools/monsters/skills').filter(f => f.endsWith('.json'))) {
  const recipe = read(`tools/monsters/skills/${file}`);
  for (const skill of recipe.skills ?? []) {
    const row = db.prepare('SELECT elementInflict FROM monster_skill WHERE monsterSkillId = ?').get(skill.ffbeId);
    const elements = inflict(row?.elementInflict);
    if (elements.length) (enemySkills[recipe.key] ??= {})[skill.id] = elements;
  }
}
for (const key of read('public/assets/content.json').characters) {
  const unitId = Number(read(`public/assets/units/${key}/character.json`).provenance?.spriteUnitId);
  const row = db.prepare('SELECT elemResistValue FROM unit WHERE unitId = ?').get(unitId);
  const values = resist(row?.elemResistValue);
  if (Object.keys(values).length) heroes[key] = values;
}
const body = `// Generated by tools/export_elements.mjs from the original FFBE database. Do not edit by hand.
// Resistances are percent (negative = weakness); elements in FFBE order: ${ELEMENTS.join(', ')}.
export const ELEMENTS = ${JSON.stringify(ELEMENTS)};
export const ENEMY_ELEMENT_RESIST = ${JSON.stringify(enemies, null, 1)};
export const ENEMY_SKILL_ELEMENTS = ${JSON.stringify(enemySkills, null, 1)};
export const HERO_ELEMENT_RESIST = ${JSON.stringify(heroes, null, 1)};
`;
const out = 'src/run/elements.mjs';
if (check) { if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) { console.error('elements.mjs is stale'); process.exit(1); } }
else fs.writeFileSync(out, body);
console.log(`enemies ${Object.keys(enemies).length} (with resistances: ${Object.values(enemies).filter(r => Object.keys(r).length).length}), `
  + `enemy skills with elements ${Object.values(enemySkills).reduce((n, s) => n + Object.keys(s).length, 0)}, heroes with resistances ${Object.keys(heroes).length}`);
