// Regenerates src/audio/basicAttackCues.ts: the original impact sound of every published body's basic
// attack. unit.effectFrames ('frame:groupId:n', '&'-separated) -> effect_group sound field
// (1fVZ3rKd, 'offset:cueId:bank') -> the first common-bank (bank 1) cue. Run after body imports
// (import_full_character.mjs does). A cue without a decoded file is reported; it stays silent until
// admitted (src/audio/combatCues.ts).
//   node tools/export_basic_attack_cues.mjs
import fs from 'node:fs';
import path from 'node:path';
import {DatabaseSync} from 'node:sqlite';

const db = new DatabaseSync('rawdata/assets/static_data/ffbe-data.db', {readOnly: true});
const unitIds = new Set();
for (const root of ['public/assets/units', 'public/assets/forms'])
  for (const dir of fs.readdirSync(root)) {
    const file = path.join(root, dir, 'manifest.json');
    if (fs.existsSync(file)) unitIds.add(String(JSON.parse(fs.readFileSync(file, 'utf8')).unitId));
  }
const unitRow = db.prepare('select effectFrames from unit where unitId=?');
const groupRow = db.prepare('select "1fVZ3rKd" as sounds from effect_group where effectGroupId=?');
const cues = {}, missing = [];
for (const id of [...unitIds].sort()) {
  const row = unitRow.get(Number(id));
  if (!row?.effectFrames) { missing.push(`${id}: no unit.effectFrames`); continue; }
  const groups = [...new Set(String(row.effectFrames).split('&').map(entry => Number(entry.split(':')[1])).filter(Number.isInteger))];
  let cue;
  for (const group of groups) {
    for (const sound of String(groupRow.get(group)?.sounds ?? '').split(',').filter(Boolean)) {
      const [, cueId, bank] = sound.split(':').map(Number);
      if (bank === 1 && Number.isInteger(cueId)) { cue = cueId; break; }
    }
    if (cue !== undefined) break;
  }
  if (cue === undefined) { missing.push(`${id}: no common-bank sound in groups ${groups.join(',')}`); continue; }
  cues[id] = {cueId: cue, sourceGroups: groups};
}
const registry = fs.readFileSync('src/audio/skillCueRegistry.ts', 'utf8') + fs.readFileSync('src/audio/combatCues.ts', 'utf8');
const undecoded = [...new Set(Object.values(cues).map(c => c.cueId))].filter(id => !registry.includes(`'SE:${id}'`));
fs.writeFileSync('src/audio/basicAttackCues.ts', '// Generated by tools/export_basic_attack_cues.mjs from unit.effectFrames and effect_group sounds.\n'
  + 'export default ' + JSON.stringify(cues, null, 2) + ' as const;\n');
console.log(JSON.stringify({units: Object.keys(cues).length, missing, undecodedCues: undecoded}, null, 1));
